pub fn scan_to_hid(scan: u16, ext: bool) -> Option<PhysicalKey> {
    let code = scan | if ext { 0x100 } else { 0 };
    TABLE
        .iter()
        .find(|(s, _)| *s == code)
        .map(|(_, h)| PhysicalKey(*h))
}
pub fn hid_to_scan(key: PhysicalKey) -> Option<(u16, bool)> {
    TABLE
        .iter()
        .find(|(_, h)| *h == key.0)
        .map(|(s, _)| (s & 0xff, s & 0x100 != 0))
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn keys_roundtrip() {
        for (_, h) in TABLE {
            let (s, e) = hid_to_scan(PhysicalKey(*h)).unwrap();
            assert_eq!(scan_to_hid(s, e), Some(PhysicalKey(*h)));
        }
    }
}
