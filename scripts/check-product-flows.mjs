// Deterministic configuration and form regressions; no daemon or native input.
import assert from 'node:assert/strict';
import {receiveConfig,editConfig,isDirty,validateConfig,pairingAddressError} from '../apps/desktop/src/configDraft.ts';
import {waitForReceipt} from '../apps/desktop/src/commandReceipt.ts';
const initial={version:1,port:24872,sharing:true,endpoints:[],links:[]};
let d=receiveConfig(null,initial);
assert.equal(isDirty(d),false);
d=editConfig(d,{...d.value,port:26000});
assert.equal(isDirty(d),true);
for(let i=0;i<20;i++)d=receiveConfig(d,{...initial});
assert.equal(d.value.port,26000,'polling preserves an edited value');
d=receiveConfig(d,{...initial,sharing:false});
assert.equal(d.value.port,26000,'pause acknowledgement preserves edits');
assert.equal(d.value.sharing,false,'sharing is live, never an editable draft');
d=receiveConfig(d,{...initial,sharing:false,endpoints:[{peer:'new-pair',address:'192.0.2.20:24872'}]});
assert.equal(d.value.port,26000,'pairing completion preserves unrelated edits');
assert.equal(d.value.endpoints.length,1,'new paired address merges into untouched fields');
assert.deepEqual(d.conflicts,[]);
d=receiveConfig(d,{...d.remote,port:27000});
assert.deepEqual(d.conflicts,[]);
assert.equal(d.value.port,27000,'saved external changes apply immediately');
d=receiveConfig(d,{...d.remote});
assert.deepEqual(d.conflicts,[],'no refresh or discard is required');
d=receiveConfig(null,d.remote);
assert.equal(d.value.port,27000,'discard restores newest backend value');
assert.equal(isDirty(d),false);
d=editConfig(d,{...d.value,port:28000});
d=receiveConfig(d,{...d.value});
assert.equal(isDirty(d),false,'matching confirmed save clears draft');
assert.deepEqual(d.conflicts,[]);
for(const value of ['','127.1','256.1.2.3','1.2.3.4:65535','1.2.3.4:0','1.2.3.4:abc','01.2.3.4','1.2.3.4:24872:4','::1','example.com'])assert.ok(pairingAddressError(value),value);
for(const value of ['192.168.1.20','127.0.0.1:24872','192.0.2.20:65534',' 192.0.2.20 '])assert.equal(pairingAddressError(value),null,value);
assert.ok(validateConfig({...initial,port:65535}));
assert.ok(validateConfig({...initial,port:NaN}));
assert.equal(validateConfig({...initial,port:65534}),null);
assert.ok(validateConfig({...initial,links:[{from:{start:.5,end:.5},to:{start:0,end:1}}]}));
assert.equal(JSON.stringify(initial),'{"version":1,"port":24872,"sharing":true,"endpoints":[],"links":[]}','reconciliation never mutates snapshots');
console.log('PASS draft polling, pause/save acknowledgement, new pairing merge, automatic remote rebase, discard, live sharing, IPv4/port validation and invalid intervals.');
let scope=receiveConfig(null,{...initial,same_subnet_only:true});
scope=editConfig(scope,{...scope.value,same_subnet_only:false});
assert.equal(isDirty(scope),true);
scope=receiveConfig(scope,{...initial,same_subnet_only:true,sharing:false});
assert.equal(scope.value.same_subnet_only,false,'polling and pause preserve pending network policy');
scope=receiveConfig(scope,{...initial,same_subnet_only:false,sharing:false});
assert.equal(isDirty(scope),false,'network policy success requires the backend value');
console.log('PASS subnet policy draft is preserved and only confirmed by backend acknowledgement.');
let time=0,reads=0,current='save';
let outcome=await waitForReceipt({id:'save',current:()=>current,now:()=>time,delay:async ms=>{time+=ms;},read:async()=>({last_command:{id:++reads===3?'save':'previous',error:null}})});
assert.equal(reads,3,'ignore stale or unrelated receipts');
assert.equal(outcome.last_command.id,'save');
outcome=await waitForReceipt({id:'save',current:()=>current,read:async()=>{current='pause';return {last_command:{id:'save',error:null}};}});
assert.equal(outcome,null,'a pause during an in-flight read suppresses stale success');
current='save';time=0;
await assert.rejects(()=>waitForReceipt({id:'save',current:()=>current,timeout:1000,now:()=>time,delay:async ms=>{time+=ms;},read:async()=>null}),/未收到后台确认/);
outcome=await waitForReceipt({id:'save',current:()=>current,read:async()=>({last_command:{id:'save',error:'rejected'}})});
assert.equal(outcome.last_command.error,'rejected','a negative receipt is preserved');
console.log('PASS request-ID matching, delayed acknowledgement, pause preemption, timeout and negative receipt.');

const prefs={...initial,tuning:{mouse_hz:250,mouse_speed:1,switch_modifier:'Ctrl',motion_wait_ms:0,edge_wait_ms:0,heartbeat_ms:100,lease_ms:750,emergency_key:41}};
let edits=receiveConfig(null,prefs);
edits=editConfig(edits,{...edits.value,tuning:{...edits.value.tuning,mouse_speed:2}});
edits=receiveConfig(edits,{...prefs,tuning:{...prefs.tuning,switch_modifier:'Shift'}});
assert.equal(edits.value.tuning.mouse_speed,2,'unrelated local typing survives remote setting update');
assert.equal(edits.value.tuning.switch_modifier,'Shift');
edits=receiveConfig(edits,{...edits.remote,tuning:{...edits.remote.tuning,mouse_speed:1.5}});
assert.equal(edits.value.tuning.mouse_speed,1.5,'new remote value wins on same setting');
assert.equal(isDirty(edits),false);
assert.equal(validateConfig(prefs),null);
assert.ok(validateConfig({...prefs,tuning:{...prefs.tuning,mouse_speed:0}}));
console.log('PASS field-wise remote preference rebase, no conflict prompt, speed validation');

// A slower receipt must not replace an edit made while that save was in flight.
let auto=receiveConfig(null,prefs);
const sent={...prefs,tuning:{...prefs.tuning,mouse_speed:2}};
auto=editConfig(auto,sent);
auto=editConfig(auto,{...sent,tuning:{...sent.tuning,mouse_speed:3}});
auto=receiveConfig(auto,{...sent,sharing:false},sent);
assert.equal(auto.value.tuning.mouse_speed,3);
assert.equal(auto.value.sharing,false);
assert.equal(isDirty(auto),true);
auto=receiveConfig(auto,{...auto.remote});
assert.equal(auto.value.tuning.mouse_speed,3,'poll after own receipt preserves queued edit');
auto=receiveConfig(auto,{...auto.remote,tuning:{...auto.remote.tuning,mouse_speed:1.5}});
assert.equal(auto.value.tuning.mouse_speed,1.5,'a later remote save still applies immediately');
assert.equal(isDirty(auto),false);
console.log('PASS autosave own-receipt rebase, queued edit, pause and subsequent remote save');
